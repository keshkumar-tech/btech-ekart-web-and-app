from django.test import TestCase
from rest_framework.test import APIClient

from .models import BlogCategory, BlogPost


class BlogTests(TestCase):
    def setUp(self):
        self.client = APIClient()
        self.cat = BlogCategory.objects.create(name="Exam Tips")
        self.post = BlogPost.objects.create(
            title="How to prepare for AKTU exams",
            category=self.cat,
            content="<p>Study smart.</p>",
            excerpt="Tips",
            is_published=True,
        )

    def test_list_and_detail(self):
        res = self.client.get("/api/blog/posts/")
        self.assertEqual(res.status_code, 200)
        self.assertEqual(res.data["count"], 1)

        res = self.client.get(f"/api/blog/posts/{self.post.slug}/")
        self.assertEqual(res.status_code, 200)
        self.assertEqual(res.data["title"], self.post.title)
        self.assertIn("content", res.data)

    def test_view_count_increments(self):
        self.client.get(f"/api/blog/posts/{self.post.slug}/")
        self.client.get(f"/api/blog/posts/{self.post.slug}/")
        self.post.refresh_from_db()
        self.assertEqual(self.post.views, 2)

    def test_unpublished_hidden(self):
        BlogPost.objects.create(title="Draft", content="x", is_published=False)
        res = self.client.get("/api/blog/posts/")
        self.assertEqual(res.data["count"], 1)

    def test_search_and_category_filter(self):
        res = self.client.get("/api/blog/posts/?q=prepare")
        self.assertEqual(res.data["count"], 1)
        res = self.client.get(f"/api/blog/posts/?category__slug={self.cat.slug}")
        self.assertEqual(res.data["count"], 1)

    def test_slug_autogenerated(self):
        self.assertEqual(self.post.slug, "how-to-prepare-for-aktu-exams")
