from django.test import TestCase

from apps.accounts.models import User
from apps.catalog.models import Branch, Category, Product, Subject


class CatalogModelTests(TestCase):
    def setUp(self):
        self.branch = Branch.objects.create(name="Computer Science & Engineering", short_name="CSE")
        self.subject = Subject.objects.create(branch=self.branch, semester=3, name="Data Structures", code="NCS-301")

    def test_product_discount_auto(self):
        # MRP 100, price 80 -> 20% off.
        p = Product.objects.create(
            title="DSA Notes", type="notes", price=80, mrp=100,
            branch=self.branch, subject=self.subject, semester=3,
        )
        self.assertEqual(p.discount, 20)

    def test_product_slug_autogenerated(self):
        p = Product.objects.create(title="My Cool Notes", price=50, mrp=60, type="notes")
        self.assertEqual(p.slug, "my-cool-notes")
        p2 = Product.objects.create(title="My Cool Notes", price=50, mrp=60, type="notes")
        self.assertEqual(p2.slug, "my-cool-notes-1")
